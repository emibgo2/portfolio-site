const VW = 720;                       // 도식 기준 폭 (반응형은 viewBox가 처리)
const esc = (s) => String(s).replace(/[&<>]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;" }[c]));

/* ---------------------------------------------------------------- 도식 DSL */
const G = {
  node(x, y, w, label, o = {}) {
    const h = o.h || 40, lines = Array.isArray(label) ? label : [label];
    const tone = o.tone ? " t-" + o.tone : "";
    const y0 = y + h / 2 + 4 - (lines.length - 1) * 7;
    const t = lines.map((l, i) => `<tspan x="${x + w / 2}" dy="${i ? 15 : 0}">${esc(l)}</tspan>`).join("");
    return `<g class="nd${tone}"><rect x="${x}" y="${y}" width="${w}" height="${h}" rx="8"/>` +
      `<text x="${x + w / 2}" y="${y0}" text-anchor="middle">${t}</text></g>`;
  },
  group(x, y, w, h, label) {
    return `<g class="grp"><rect x="${x}" y="${y}" width="${w}" height="${h}" rx="10"/>` +
      `<text x="${x + 14}" y="${y + 19}">${esc(label)}</text></g>`;
  },
  note(x, y, text, cls = "anno", anchor = "start") {
    return `<text class="${cls}" x="${x}" y="${y}" text-anchor="${anchor}">${esc(text)}</text>`;
  },
  /* 직선/꺾은 화살표. d: path 데이터, e: 라벨, ex/ey: 라벨 위치, ea: 라벨 정렬 */
  p(d, o = {}) {
    const cls = o.k || "e";
    const lab = o.e ? `<text class="elab" x="${o.ex}" y="${o.ey}" text-anchor="${o.ea || "start"}">${esc(o.e)}</text>` : "";
    return `<path class="${cls}" d="${d}"/>` + lab;
  },
  v(x, y1, y2, o = {}) { return G.p(`M${x},${y1} L${x},${y2}`, o); },
  h(y, x1, x2, o = {}) { return G.p(`M${x1},${y} L${x2},${y}`, o); },
  elbow(x1, y1, x2, y2, o = {}) {                        // 가로 → 세로
    const mx = (x1 + x2) / 2;
    return G.p(`M${x1},${y1} L${mx},${y1} L${mx},${y2} L${x2},${y2}`, o);
  },
  chip(x, y, w, label) {
    return `<g class="nd t-dim"><rect x="${x}" y="${y}" width="${w}" height="26" rx="6"/>` +
      `<text x="${x + w / 2}" y="${y + 17}" text-anchor="middle">${esc(label)}</text></g>`;
  },
  box(x, y, w, h, label, o = {}) {
    return `<g class="grp"><rect x="${x}" y="${y}" width="${w}" height="${h}" rx="10"/>` +
      `<text x="${x + 14}" y="${y + 19}">${esc(label)}</text></g>`;
  },
  bar(x, y, w, h, cls) { return `<rect class="${cls}" x="${x}" y="${y}" width="${w}" height="${h}" rx="3"/>`; },
  strike(x1, y1, x2, y2) { return `<line class="strike" x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}"/>`; },
  svg(h, body) {
    return `<svg class="dg" viewBox="0 0 ${VW} ${h}" role="img" aria-label="도식">${body}</svg>`;
  }
};

